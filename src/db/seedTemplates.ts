export async function ensureSeededTemplates() {
  const existing = await db.select({ value: count() }).from(templates);
  if ((existing[0]?.value ?? 0) === 0) {
    await db.insert(templates).values(
      INITIAL_ADMIN_TEMPLATES.map((tpl) => ({
        name: tpl.name,
        category: tpl.category,
        orientation: tpl.orientation,
        backgroundUrl: tpl.backgroundUrl,
        isPremiumOnly: tpl.isPremiumOnly,
        isBlocked: false,
        fields: tpl.fields,
      }))
    );
  }
}
